-- Tables that live IN Exasol. Re-running this empties them (02_sources.sh reloads them straight after).
CREATE SCHEMA IF NOT EXISTS LOS_BOOK;
CREATE SCHEMA IF NOT EXISTS LOS_SRC;
CREATE SCHEMA IF NOT EXISTS LOS_POLICY;

-- The historical book: every Lending Club loan 2007-2018 with a FINAL outcome, as application-time facts + realised cash.
CREATE OR REPLACE TABLE LOS_BOOK.LOANS (
  LOAN_ID DECIMAL(12,0), ISSUE_DATE DATE, TERM_MONTHS DECIMAL(3,0), LOAN_AMOUNT DECIMAL(12,2), FUNDED_AMOUNT DECIMAL(12,2),
  INT_RATE DECIMAL(6,2), INSTALMENT DECIMAL(10,2), LC_GRADE VARCHAR(2), EMP_YEARS DECIMAL(2,0), ANNUAL_INCOME DECIMAL(14,2),
  INCOME_VERIFIED DECIMAL(1,0), DTI_BEFORE DECIMAL(8,2), FOIR_AFTER DECIMAL(10,2), LOAN_TO_INCOME DECIMAL(10,4),
  REVOL_UTIL DECIMAL(6,1), DELINQ_2Y DECIMAL(4,0), INQ_6M DECIMAL(4,0), PUB_REC DECIMAL(4,0), OPEN_ACCOUNTS DECIMAL(4,0),
  BUREAU_SCORE DECIMAL(4,0), PURPOSE VARCHAR(40), OUTCOME VARCHAR(20), DEFAULTED DECIMAL(1,0),
  TOTAL_PAID DECIMAL(14,2), INTEREST_PAID DECIMAL(14,2), RECOVERIES DECIMAL(14,2), NET_CASH DECIMAL(14,2));

-- What the credit bureau returned for each application (mocked: no bureau is called).
CREATE OR REPLACE TABLE LOS_SRC.BUREAU_PULLS (
  APP_ID VARCHAR(20), CUST_ID VARCHAR(12), PULLED_AT TIMESTAMP, BUREAU_SCORE DECIMAL(4,0), INQ_6M DECIMAL(3,0),
  PUB_REC DECIMAL(3,0), ACTIVE_LOANS DECIMAL(3,0), EXISTING_EMI DECIMAL(12,0), OLDEST_TRADE_YEARS DECIMAL(4,1));

-- The scorecard IS a table: one row per feature, weight on the raw scale, the book average, and the reason code.
CREATE OR REPLACE TABLE LOS_POLICY.SCORECARD (
  FEATURE VARCHAR(30), CLIP_LOW DOUBLE, CLIP_HIGH DOUBLE, WEIGHT DOUBLE, BOOK_MEAN DOUBLE, REASON VARCHAR(120), ORDINAL DECIMAL(2,0));
