-- Scoring, reason codes, rules, pricing and affordability: all SQL over tables the risk team owns.
-- Every view is computed for BOTH the LIVE and the DRAFT policy (column POLICY_STATUS), so a proposed change can be
-- compared with the running one before anyone publishes it.

-- ---------------------------------------------------------------- the model, as rows
CREATE OR REPLACE VIEW LOS_POLICY.WEIGHTS AS          -- the scorecard pivoted to one row
SELECT MAX(CASE WHEN FEATURE = '_INTERCEPT'     THEN WEIGHT END) AS B0,
       MAX(CASE WHEN FEATURE = 'BUREAU_SCORE'   THEN WEIGHT END) AS W_BUREAU,
       MAX(CASE WHEN FEATURE = 'FOIR_AFTER'     THEN WEIGHT END) AS W_FOIR,
       MAX(CASE WHEN FEATURE = 'LOAN_TO_INCOME' THEN WEIGHT END) AS W_LTI,
       MAX(CASE WHEN FEATURE = 'INQ_6M'         THEN WEIGHT END) AS W_INQ,
       MAX(CASE WHEN FEATURE = 'EMP_YEARS'      THEN WEIGHT END) AS W_EMP,
       MAX(CASE WHEN FEATURE = 'TERM_60'        THEN WEIGHT END) AS W_TERM,
       MAX(CASE WHEN FEATURE = 'PUB_REC'        THEN WEIGHT END) AS W_PUB,
       (SELECT FACTOR FROM LOS_POLICY.MODEL) AS FACTOR, (SELECT BASE_SCORE FROM LOS_POLICY.MODEL) AS BASE_SCORE,
       (SELECT LN(BASE_ODDS) FROM LOS_POLICY.MODEL) AS LN_ODDS
FROM LOS_POLICY.SCORECARD;

-- ---------------------------------------------------------------- the pipeline: features for the scorecard
CREATE OR REPLACE VIEW LOS_CORE.APPLICATION_FEATURES AS
WITH p AS (SELECT * FROM LOS_POLICY.POLICY WHERE STATUS IN ('LIVE', 'DRAFT'))
SELECT p.STATUS AS POLICY_STATUS, p.POLICY_VERSION, f.APP_ID,
       -- affordability is tested at the assessment rate, so the score cannot depend on the price it decides
       ROUND(f.AMOUNT_REQUESTED * (p.ASSESSMENT_RATE / 1200) / (1 - POWER(1 + p.ASSESSMENT_RATE / 1200, -f.TERM_MONTHS)), 0) AS EMI_ASSESSED,
       COALESCE(f.BUREAU_SCORE, (SELECT BOOK_MEAN FROM LOS_POLICY.SCORECARD WHERE FEATURE = 'BUREAU_SCORE')) AS X_BUREAU,
       ROUND(100 * (f.EXISTING_EMI + f.AMOUNT_REQUESTED * (p.ASSESSMENT_RATE / 1200) / (1 - POWER(1 + p.ASSESSMENT_RATE / 1200, -f.TERM_MONTHS)))
             / NULLIF(f.VERIFIED_GROSS, 0), 2) AS X_FOIR,
       ROUND(f.AMOUNT_REQUESTED / NULLIF(f.VERIFIED_GROSS * 12, 0), 4) AS X_LTI,
       COALESCE(f.INQ_6M, 0) AS X_INQ, COALESCE(f.EMP_YEARS, 0) AS X_EMP,
       CASE WHEN f.TERM_MONTHS >= 60 THEN 1 ELSE 0 END AS X_TERM, COALESCE(f.PUB_REC, 0) AS X_PUB
FROM LOS_CORE.APPLICATION_FACTS f CROSS JOIN p;

-- each feature's contribution in points versus the average loan in the book: the reason codes (exact for a linear model)
CREATE OR REPLACE VIEW LOS_CORE.SCORE_CONTRIBUTIONS AS
WITH x AS (
  SELECT POLICY_STATUS, APP_ID, 'BUREAU_SCORE' AS FEATURE, X_BUREAU AS X FROM LOS_CORE.APPLICATION_FEATURES UNION ALL
  SELECT POLICY_STATUS, APP_ID, 'FOIR_AFTER', X_FOIR FROM LOS_CORE.APPLICATION_FEATURES UNION ALL
  SELECT POLICY_STATUS, APP_ID, 'LOAN_TO_INCOME', X_LTI FROM LOS_CORE.APPLICATION_FEATURES UNION ALL
  SELECT POLICY_STATUS, APP_ID, 'INQ_6M', X_INQ FROM LOS_CORE.APPLICATION_FEATURES UNION ALL
  SELECT POLICY_STATUS, APP_ID, 'EMP_YEARS', X_EMP FROM LOS_CORE.APPLICATION_FEATURES UNION ALL
  SELECT POLICY_STATUS, APP_ID, 'TERM_60', X_TERM FROM LOS_CORE.APPLICATION_FEATURES UNION ALL
  SELECT POLICY_STATUS, APP_ID, 'PUB_REC', X_PUB FROM LOS_CORE.APPLICATION_FEATURES)
SELECT x.POLICY_STATUS, x.APP_ID, x.FEATURE, x.X AS FEATURE_VALUE, s.BOOK_MEAN,
       ROUND(-(SELECT FACTOR FROM LOS_POLICY.MODEL) * s.WEIGHT * (LEAST(GREATEST(x.X, s.CLIP_LOW), s.CLIP_HIGH) - s.BOOK_MEAN), 1) AS POINTS,
       s.REASON, s.ORDINAL
FROM x JOIN LOS_POLICY.SCORECARD s ON s.FEATURE = x.FEATURE;

CREATE OR REPLACE VIEW LOS_CORE.SCORES AS
SELECT a.POLICY_STATUS, a.APP_ID, a.EMI_ASSESSED, a.X_FOIR AS FOIR_PCT, a.X_LTI AS LOAN_TO_INCOME,
       ROUND(w.BASE_SCORE - w.FACTOR * (w.B0 + w.W_BUREAU * LEAST(GREATEST(a.X_BUREAU, 300), 850) + w.W_FOIR * LEAST(GREATEST(a.X_FOIR, 0), 60)
             + w.W_LTI * LEAST(GREATEST(a.X_LTI, 0), 1) + w.W_INQ * LEAST(a.X_INQ, 6) + w.W_EMP * LEAST(a.X_EMP, 10)
             + w.W_TERM * a.X_TERM + w.W_PUB * LEAST(a.X_PUB, 3) + w.LN_ODDS), 0) AS SCORE,
       ROUND(100 / (1 + EXP(-(w.B0 + w.W_BUREAU * LEAST(GREATEST(a.X_BUREAU, 300), 850) + w.W_FOIR * LEAST(GREATEST(a.X_FOIR, 0), 60)
             + w.W_LTI * LEAST(GREATEST(a.X_LTI, 0), 1) + w.W_INQ * LEAST(a.X_INQ, 6) + w.W_EMP * LEAST(a.X_EMP, 10)
             + w.W_TERM * a.X_TERM + w.W_PUB * LEAST(a.X_PUB, 3)))), 1) AS PD_PCT
FROM LOS_CORE.APPLICATION_FEATURES a CROSS JOIN LOS_POLICY.WEIGHTS w;

-- ---------------------------------------------------------------- pricing and affordability
CREATE OR REPLACE VIEW LOS_CORE.OFFERS AS
WITH p AS (SELECT * FROM LOS_POLICY.POLICY WHERE STATUS IN ('LIVE', 'DRAFT')),
o AS (
  SELECT s.POLICY_STATUS, s.APP_ID, s.SCORE, s.PD_PCT, s.FOIR_PCT, s.LOAN_TO_INCOME, s.EMI_ASSESSED, r.BAND,
         p.BASE_RATE + r.RISK_PREMIUM AS RATE,
         GREATEST(p.FOIR_CAP / 100 * f.VERIFIED_GROSS - f.EXISTING_EMI, 0) AS MAX_EMI,
         p.ASSESSMENT_RATE / 1200 AS RA, f.TERM_MONTHS, f.AMOUNT_REQUESTED, p.MAX_LOAN, p.FOIR_CAP, p.FOIR_NEAR_BAND
  FROM LOS_CORE.SCORES s
  JOIN p ON p.STATUS = s.POLICY_STATUS
  JOIN LOS_CORE.APPLICATION_FACTS f ON f.APP_ID = s.APP_ID
  JOIN LOS_POLICY.RATE_BANDS r ON s.SCORE >= r.SCORE_FROM AND s.SCORE < r.SCORE_TO)
SELECT o.*, LEAST(o.MAX_LOAN, FLOOR(o.MAX_EMI * (1 - POWER(1 + o.RA, -o.TERM_MONTHS)) / o.RA / 10000) * 10000) AS MAX_AMOUNT,
       LEAST(o.AMOUNT_REQUESTED, LEAST(o.MAX_LOAN, FLOOR(o.MAX_EMI * (1 - POWER(1 + o.RA, -o.TERM_MONTHS)) / o.RA / 10000) * 10000)) AS OFFER_AMOUNT
FROM o;

-- ---------------------------------------------------------------- the rules: one metric per row, compared with the table's threshold
CREATE OR REPLACE VIEW LOS_CORE.RULE_METRICS AS
WITH p AS (SELECT * FROM LOS_POLICY.POLICY WHERE STATUS IN ('LIVE', 'DRAFT')),
m AS (
  SELECT o.POLICY_STATUS, o.SCORE, o.FOIR_PCT, o.MAX_AMOUNT, o.OFFER_AMOUNT, f.*,
         p.APPROVE_FROM, p.DECLINE_BELOW, p.AUTO_APPROVE_LIMIT, p.MIN_LOAN, p.MIN_AGE, p.FOIR_CAP, p.FOIR_NEAR_BAND
  FROM LOS_CORE.OFFERS o JOIN p ON p.STATUS = o.POLICY_STATUS
  JOIN LOS_CORE.APPLICATION_FACTS f ON f.APP_ID = o.APP_ID),
cr AS (                                      -- data contracts (sql/50_semantic.sql): critical breaches per application
  SELECT r.APP_ID, SUM(CASE WHEN NOT r.PASSED AND k.SEVERITY = 'CRITICAL' THEN 1 ELSE 0 END) AS CRIT,
         GROUP_CONCAT(CASE WHEN NOT r.PASSED AND k.SEVERITY = 'CRITICAL' THEN r.CONTRACT_ID || ' ' || r.EVIDENCE END SEPARATOR '; ') AS WHAT
  FROM LOS_SEM.CONTRACT_RESULTS r JOIN LOS_SEM.CONTRACTS k ON k.CONTRACT_ID = r.CONTRACT_ID GROUP BY r.APP_ID)
SELECT m.POLICY_STATUS, m.APP_ID, 'CRITICAL_CONTRACT_BREACHES' AS METRIC, COALESCE(cr.CRIT, 0) AS VAL,
       COALESCE(cr.WHAT, 'all critical contracts kept') AS EVIDENCE FROM m LEFT JOIN cr ON cr.APP_ID = m.APP_ID UNION ALL
SELECT POLICY_STATUS, APP_ID, 'POINTS_BELOW_APPROVE' AS METRIC, APPROVE_FROM - SCORE AS VAL, 'score ' || SCORE || ' vs approve from ' || APPROVE_FROM AS EVIDENCE FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'POINTS_BELOW_DECLINE', DECLINE_BELOW - SCORE, 'score ' || SCORE || ' vs decline below ' || DECLINE_BELOW FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'INCOME_GAP_PCT', INCOME_GAP_PCT, 'payslip net ' || TO_CHAR(PAYSLIP_NET, '9999999') || ' vs 6-month bank average ' || TO_CHAR(ROUND(BANK_SALARY_AVG), '9999999') FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'MIN_KEY_CONFIDENCE', MIN_KEY_CONFIDENCE, 'lowest key-field confidence ' || MIN_KEY_CONFIDENCE FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'FOIR_NEAR_CAP', CASE WHEN FOIR_PCT > FOIR_CAP - FOIR_NEAR_BAND AND FOIR_PCT <= FOIR_CAP THEN 1 ELSE 0 END,
       'FOIR ' || FOIR_PCT || '% vs cap ' || FOIR_CAP || '%' FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'BUREAU_MISSING', BUREAU_MISSING, 'no bureau record' FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'EMP_YEARS', EMP_YEARS, EMP_YEARS || ' years with ' || EMPLOYER FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'RETURNED_DEBITS_6M', RETURNED_DEBITS_6M, RETURNED_DEBITS_6M || ' returned debits in six months' FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'GAMING_PCT', GAMING_PCT, GAMING_PCT || '% of credits spent on online gaming' FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'SALARY_GAPS_6M', CASE WHEN BANK_CUSTOMER = 0 THEN 0 ELSE 6 - SALARY_MONTHS END,
       CASE WHEN BANK_CUSTOMER = 0 THEN 'not a bank customer: income from the documents' ELSE SALARY_MONTHS || ' of 6 months with salary' END FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'SALARY_CV_PCT', SALARY_CV_PCT, 'salary varies ' || SALARY_CV_PCT || '% month to month' FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'AMOUNT_OVER_LIMIT', OFFER_AMOUNT - AUTO_APPROVE_LIMIT, 'amount ' || TO_CHAR(OFFER_AMOUNT, '99999999') || ' vs limit ' || TO_CHAR(AUTO_APPROVE_LIMIT, '99999999') FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'ID_NAME_MISMATCH', ID_NAME_MISMATCH, 'ID says ' || NAME_ON_ID || ', application says ' || APPLICANT_NAME FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'MAX_AMOUNT_SHORTFALL', MIN_LOAN - MAX_AMOUNT, 'affordable maximum ' || TO_CHAR(MAX_AMOUNT, '99999999') FROM m UNION ALL
SELECT POLICY_STATUS, APP_ID, 'UNDER_MIN_AGE', CASE WHEN AGE_YEARS < MIN_AGE THEN 1 ELSE 0 END, 'below the minimum age of ' || MIN_AGE FROM m;

CREATE OR REPLACE VIEW LOS_CORE.RULE_HITS AS
SELECT m.POLICY_STATUS, m.APP_ID, r.RULE_ID, r.TITLE, r.OUTCOME, r.REVIEW_LEVEL, r.WHY_A_PERSON, m.VAL, r.THRESHOLD, m.EVIDENCE
FROM LOS_CORE.RULE_METRICS m
JOIN LOS_POLICY.REFERRAL_RULES r ON r.METRIC = m.METRIC AND r.ENABLED
WHERE (r.OPERATOR = '>'  AND m.VAL >  r.THRESHOLD) OR (r.OPERATOR = '>=' AND m.VAL >= r.THRESHOLD)
   OR (r.OPERATOR = '<'  AND m.VAL <  r.THRESHOLD) OR (r.OPERATOR = '<=' AND m.VAL <= r.THRESHOLD)
   OR (r.OPERATOR = '='  AND m.VAL =  r.THRESHOLD);

-- ---------------------------------------------------------------- the system's decision (a person may still decide otherwise)
CREATE OR REPLACE VIEW LOS_CORE.DECISIONS AS
WITH h AS (
  SELECT POLICY_STATUS, APP_ID,
         MAX(CASE WHEN OUTCOME = 'DECLINE' THEN 1 ELSE 0 END) AS ANY_DECLINE,
         MAX(CASE WHEN OUTCOME = 'REFER' THEN 1 ELSE 0 END) AS ANY_REFER,
         MAX(CASE REVIEW_LEVEL WHEN 'FRAUD' THEN 3 WHEN 'UW2' THEN 2 WHEN 'UW1' THEN 1 ELSE 0 END) AS LVL,
         GROUP_CONCAT(RULE_ID ORDER BY RULE_ID SEPARATOR ',') AS RULES_FIRED,
         GROUP_CONCAT(TITLE ORDER BY RULE_ID SEPARATOR ' · ') AS RULE_TITLES
  FROM LOS_CORE.RULE_HITS GROUP BY POLICY_STATUS, APP_ID)
SELECT o.POLICY_STATUS, o.APP_ID, f.APPLICANT_NAME, f.SUBMITTED_AT, f.CHANNEL, f.AMOUNT_REQUESTED, f.TERM_MONTHS, f.PURPOSE,
       f.EMPLOYER, f.CITY, o.SCORE, o.PD_PCT, o.BAND, o.RATE, o.FOIR_PCT, o.MAX_AMOUNT, o.OFFER_AMOUNT,
       ROUND(o.OFFER_AMOUNT * (o.RATE / 1200) / (1 - POWER(1 + o.RATE / 1200, -o.TERM_MONTHS)), 0) AS EMI_AT_OFFER,
       CASE WHEN h.ANY_DECLINE = 1 THEN 'DECLINE'
            WHEN h.ANY_REFER = 1 THEN 'REFER'
            WHEN o.OFFER_AMOUNT < o.AMOUNT_REQUESTED THEN 'APPROVE_REDUCED'
            ELSE 'APPROVE' END AS SYSTEM_DECISION,
       CASE WHEN h.ANY_DECLINE = 1 THEN NULL ELSE CASE h.LVL WHEN 3 THEN 'FRAUD' WHEN 2 THEN 'UW2' WHEN 1 THEN 'UW1' END END AS REVIEW_LEVEL,
       h.RULES_FIRED, h.RULE_TITLES
FROM LOS_CORE.OFFERS o
JOIN LOS_CORE.APPLICATION_FACTS f ON f.APP_ID = o.APP_ID
LEFT JOIN h ON h.APP_ID = o.APP_ID AND h.POLICY_STATUS = o.POLICY_STATUS;

-- top three reasons pulling a score down (shown to the underwriter; usable as adverse-action reasons)
CREATE OR REPLACE VIEW LOS_CORE.REASON_CODES AS
SELECT POLICY_STATUS, APP_ID, FEATURE, FEATURE_VALUE, POINTS, REASON
FROM LOS_CORE.SCORE_CONTRIBUTIONS
WHERE POINTS < 0
QUALIFY ROW_NUMBER() OVER (PARTITION BY POLICY_STATUS, APP_ID ORDER BY POINTS) <= 3;
